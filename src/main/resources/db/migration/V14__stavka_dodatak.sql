-- Dodaci vezani za stavku porudžbine (npr. Nutela uz palačinku).
-- Cena je snapshot u trenutku porudžbine, da kasnija promena cenovnika
-- ne menja već napravljene porudžbine.
CREATE TABLE IF NOT EXISTS stavka_dodatak (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stavka_id BIGINT NOT NULL,
    proizvod_id BIGINT NOT NULL,
    kolicina DOUBLE PRECISION NOT NULL DEFAULT 1,
    cena NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_stavka_dodatak_stavka
        FOREIGN KEY (stavka_id) REFERENCES stavka_porudzbine(id) ON DELETE CASCADE,
    CONSTRAINT fk_stavka_dodatak_proizvod
        FOREIGN KEY (proizvod_id) REFERENCES proizvod(id)
);

CREATE INDEX IF NOT EXISTS idx_stavka_dodatak_stavka_id ON stavka_dodatak(stavka_id);
