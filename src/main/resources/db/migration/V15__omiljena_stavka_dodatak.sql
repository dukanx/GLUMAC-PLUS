-- Dodaci zapamćeni uz stavku omiljene porudžbine.
-- Bez kolone `cena` (za razliku od stavka_dodatak): omiljena porudžbina je
-- šablon, pa se cena uzima ona koja važi kad se šablon iskoristi.
CREATE TABLE IF NOT EXISTS omiljena_stavka_dodatak (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    omiljena_stavka_id BIGINT NOT NULL,
    proizvod_id BIGINT NOT NULL,
    kolicina DOUBLE PRECISION NOT NULL DEFAULT 1,
    CONSTRAINT fk_omilj_dodatak_stavka
        FOREIGN KEY (omiljena_stavka_id) REFERENCES omiljena_porudzbina_stavka(id) ON DELETE CASCADE,
    CONSTRAINT fk_omilj_dodatak_proizvod
        FOREIGN KEY (proizvod_id) REFERENCES proizvod(id)
);

CREATE INDEX IF NOT EXISTS idx_omilj_dodatak_stavka_id
    ON omiljena_stavka_dodatak(omiljena_stavka_id);
